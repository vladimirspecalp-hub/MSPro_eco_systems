// Генерация slug из текста
function generateSlug(text) {
  const translitMap = {
    'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'yo', 'ж': 'zh',
    'з': 'z', 'и': 'i', 'й': 'j', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o',
    'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'h', 'ц': 'c',
    'ч': 'ch', 'ш': 'sh', 'щ': 'shch', 'ъ': '', 'ы': 'y', 'ь': '', 'э': 'e', 'ю': 'yu',
    'я': 'ya', ' ': '-', ',': '', '.': ''
  };

  return text
    .toLowerCase()
    .split('')
    .map(char => translitMap[char] || char)
    .join('')
    .replace(/[^a-z0-9-]/g, '')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

// Получение CTA по типу услуги
function getCTA(phrase) {
  if (phrase.includes('покраска')) return 'Заказать покраску';
  if (phrase.includes('ремонт')) return 'Заказать ремонт';
  if (phrase.includes('монтаж')) return 'Заказать монтаж';
  if (phrase.includes('защита')) return 'Заказать защиту';
  if (phrase.includes('очистка')) return 'Заказать очистку';
  if (phrase.includes('огнезащита')) return 'Заказать огнезащиту';
  if (phrase.includes('обследование')) return 'Заказать обследование';
  if (phrase.includes('консультация')) return 'Получить консультацию';
  if (phrase.includes('расчет')) return 'Получить расчет';
  return 'Заказать услугу';
}

// Генерация SEO записей
function generateSEOEntries() {
  const entries = [];
  const usedSlugs = new Set();

  // Загружаем существующие slug'и
  const existingSlugs = fs.readFileSync('/tmp/existing_slugs.txt', 'utf8')
    .split('\n')
    .filter(Boolean);
  
  existingSlugs.forEach(slug => usedSlugs.add(slug));

  console.log(`Загружено ${existingSlugs.length} существующих slug'ов`);

  // Генерируем комбинации
  for (const phrase of phrases) {
    for (const modifier of modifiers) {
      const combinedText = `${phrase} ${modifier.text}`;
      const slug = generateSlug(combinedText);

      // Проверяем дубликаты
      if (usedSlugs.has(slug)) {
        console.log(`Пропускаем дубликат: ${slug}`);
        continue;
      }

      usedSlugs.add(slug);

      // Создаём title
      const title = `${phrase.charAt(0).toUpperCase() + phrase.slice(1)} ${modifier.text} — MSPRO`;

      // Создаём description
      const description = `${phrase.charAt(0).toUpperCase() + phrase.slice(1)} ${modifier.text}. Профессиональные услуги промышленного альпинизма MSPRO. Лицензии, сертификаты, гарантия качества.`;

      // Создаём keywords
      const keywords = [
        phrase,
        modifier.text,
        'MSPRO',
        'промышленный альпинизм'
      ];

      entries.push({
        slug,
        title: title.substring(0, 100), // Ограничиваем длину
        description: description.substring(0, 160), // SEO лимит
        cta: getCTA(phrase),
        region: modifier.region,
        keywords
      });
    }
  }

  console.log(`Сгенерировано ${entries.length} новых SEO записей`);
  return entries;
}

// Разбивка на файлы по 500 записей
function splitIntoFiles(entries) {
  const filesData = [];
  const chunkSize = 500;

  for (let i = 0; i < entries.length; i += chunkSize) {
    const chunk = entries.slice(i, i + chunkSize);
    filesData.push(chunk);
  }

  return filesData;
}

// Основная функция
async function main() {
  console.log('🚀 Начинаем генерацию SEO ядра...\n');

  // Генерируем новые записи
  const newEntries = generateSEOEntries();

  // Читаем существующие записи
  const existingEntries = JSON.parse(
    fs.readFileSync(path.join(__dirname, '../content/seo_core.json'), 'utf8')
  );

  console.log(`\nСуществующих записей: ${existingEntries.length}`);
  console.log(`Новых записей: ${newEntries.length}`);

  // Объединяем все записи
  const allEntries = [...existingEntries, ...newEntries];
  console.log(`Всего записей: ${allEntries.length}\n`);

  // Разбиваем на файлы
  const files = splitIntoFiles(allEntries);

  console.log(`Создаём ${files.length} файлов:\n`);

  // Сохраняем файлы
  files.forEach((entries, index) => {
    const filename = index === 0
      ? 'seo_core.json'
      : `seo_core_part${index + 1}.json`;

    const filepath = path.join(__dirname, '../content', filename);
    fs.writeFileSync(filepath, JSON.stringify(entries, null, 2));
    console.log(`✅ ${filename} — ${entries.length} записей`);
  });

  console.log('\n✨ Генерация завершена!');
}

main().catch(console.error);
