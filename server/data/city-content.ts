// Simple hash function to select variants deterministically based on slug
export function getMixerVariant(slug: string, variantsCount: number): number {
    let hash = 0;
    for (let i = 0; i < slug.length; i++) {
        const char = slug.charCodeAt(i);
        hash = ((hash << 5) - hash) + char;
        hash = hash & hash; // Convert to 32bit integer
    }
    return Math.abs(hash) % variantsCount;
}

export function getBenefitsForSlug(slug: string): string[] {
    const sets = Object.values(BENEFIT_SETS);
    const index = getMixerVariant(slug, sets.length);
    return sets[index];
}

export function getFAQForSlug(slug: string, cityName: string): { question: string, answer: string }[] {
    const index = getMixerVariant(slug, FAQ_VARIANTS.length);
    const template = FAQ_VARIANTS[index];

    // Inject city name
    return template.map(item => ({
        question: item.question.replace(/{{CITY}}/g, cityName),
        answer: item.answer.replace(/{{CITY}}/g, cityName)
    }));
}

